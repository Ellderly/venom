package dev.ellderly.venom.client.render;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.core.Direction;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.EnumSet;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Loads the cube models generated by {@code tools/gen_assets.py} (assets/venom/geo/*.json) into vanilla
 * {@link ModelPart}s. Geometry and textures come from the same source, so they can never drift apart.
 */
public final class GeoModel {
    public final ModelPart root;
    private final Map<String, ModelPart> parts = new HashMap<>();

    private GeoModel(ModelPart root) {
        this.root = root;
    }

    public ModelPart part(String name) {
        ModelPart p = parts.get(name);
        if (p == null) throw new IllegalArgumentException("Unknown model part: " + name);
        return p;
    }

    public void resetPose() {
        for (ModelPart p : parts.values()) p.resetPose();
    }

    public static GeoModel load(String name) {
        String path = "/assets/venom/geo/" + name + ".json";
        try (InputStream in = GeoModel.class.getResourceAsStream(path)) {
            if (in == null) throw new IllegalStateException("Missing model " + path);
            JsonObject json = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
            JsonArray tex = json.getAsJsonArray("texture");
            float tw = tex.get(0).getAsFloat(), th = tex.get(1).getAsFloat();
            Map<String, List<JsonObject>> byParent = new LinkedHashMap<>();
            for (JsonElement e : json.getAsJsonArray("parts")) {
                JsonObject o = e.getAsJsonObject();
                String parent = o.get("parent").isJsonNull() ? "" : o.get("parent").getAsString();
                byParent.computeIfAbsent(parent, k -> new ArrayList<>()).add(o);
            }
            Map<String, ModelPart> top = new LinkedHashMap<>();
            GeoModel model = new GeoModel(null);
            for (JsonObject o : byParent.getOrDefault("", List.of())) {
                top.put(o.get("name").getAsString(), build(o, byParent, tw, th, model.parts));
            }
            GeoModel result = new GeoModel(new ModelPart(List.of(), top));
            result.parts.putAll(model.parts);
            return result;
        } catch (java.io.IOException ex) {
            throw new IllegalStateException("Failed to read model " + path, ex);
        }
    }

    private static ModelPart build(JsonObject o, Map<String, List<JsonObject>> byParent, float tw, float th, Map<String, ModelPart> out) {
        String name = o.get("name").getAsString();
        List<ModelPart.Cube> cubes = new ArrayList<>();
        for (JsonElement ce : o.getAsJsonArray("cubes")) {
            JsonObject c = ce.getAsJsonObject();
            JsonArray org = c.getAsJsonArray("o"), size = c.getAsJsonArray("s"), uv = c.getAsJsonArray("uv"), inf = c.getAsJsonArray("inf");
            cubes.add(new ModelPart.Cube(uv.get(0).getAsInt(), uv.get(1).getAsInt(),
                    org.get(0).getAsFloat(), org.get(1).getAsFloat(), org.get(2).getAsFloat(),
                    size.get(0).getAsFloat(), size.get(1).getAsFloat(), size.get(2).getAsFloat(),
                    inf.get(0).getAsFloat(), inf.get(1).getAsFloat(), inf.get(2).getAsFloat(),
                    c.get("mirror").getAsBoolean(), tw, th, EnumSet.allOf(Direction.class)));
        }
        Map<String, ModelPart> children = new LinkedHashMap<>();
        for (JsonObject child : byParent.getOrDefault(name, List.of())) {
            children.put(child.get("name").getAsString(), build(child, byParent, tw, th, out));
        }
        ModelPart part = new ModelPart(cubes, children);
        JsonArray piv = o.getAsJsonArray("pivot"), rot = o.getAsJsonArray("rot");
        part.setInitialPose(PartPose.offsetAndRotation(piv.get(0).getAsFloat(), piv.get(1).getAsFloat(), piv.get(2).getAsFloat(),
                rot.get(0).getAsFloat(), rot.get(1).getAsFloat(), rot.get(2).getAsFloat()));
        part.resetPose();
        out.put(name, part);
        return part;
    }
}
